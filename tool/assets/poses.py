"""Cut the villager pose sheets (one per persona, three poses left to
right) into single figures, write the app's WebP files and the table of
where each pose's face is (for the puppet cards).

Usage: python tool/assets/poses.py design/sheets/poses/*.png

A sheet `design/sheets/poses/<persona>.png` becomes
`design/source/figures/poses/<persona>_<n>.png` and
`app/assets/figures/poses/<persona>_<n>.webp` (560 px high), n = 1..3.
All poses on disk end up in `app/lib/src/game/poses.g.dart`.
"""

import subprocess
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

SOURCE = Path("design/source/figures/poses")
APP = Path("app/assets/figures/poses")
TABLE = Path("app/lib/src/game/poses.g.dart")
HEIGHT = 560
POSES = 3


def split_by_columns(sheet: Path, names: list[str]) -> None:
    """Fallback when figures touch: cut at the emptiest column near each
    expected border, keep the largest region of each piece, trim it."""
    rgba = np.array(Image.open(sheet).convert("RGBA"))
    alpha = rgba[:, :, 3].astype(float)
    density = np.convolve(alpha.sum(axis=0), np.ones(15) / 15, mode="same")
    width = rgba.shape[1]
    step = width / len(names)
    cuts = [0]
    for k in range(1, len(names)):
        lo, hi = int((k - 0.35) * step), int((k + 0.35) * step)
        cuts.append(lo + int(np.argmin(density[lo:hi])))
    cuts.append(width)
    for name, x0, x1 in zip(names, cuts, cuts[1:]):
        piece = rgba[:, x0:x1].copy()
        labels, count = ndimage.label(piece[:, :, 3] > 48)
        sizes = ndimage.sum(np.ones_like(labels), labels, range(1, count + 1))
        largest = int(np.argmax(sizes)) + 1
        edges = set(labels[:, 0]) | set(labels[:, -1])
        drop = [i for i in edges if i not in (0, largest)]
        piece[np.isin(labels, drop), 3] = 0
        ys, xs = np.nonzero(piece[:, :, 3] > 48)
        crop = piece[max(ys.min() - 8, 0) : ys.max() + 9, max(xs.min() - 8, 0) : xs.max() + 9]
        Image.fromarray(crop).save(SOURCE / f"{name}.png", optimize=True)


def face(image: Image.Image) -> tuple[float, float, float]:
    """Where the face is: the middle of the top of the silhouette, a little
    below its crown; as fractions, and the aspect ratio."""
    alpha = np.array(image)[:, :, 3] > 64
    rows = np.nonzero(alpha.any(axis=1))[0]
    top, bottom = rows.min(), rows.max()
    height = bottom - top
    band = alpha[top : top + max(int(height * 0.1), 4)]
    xs = np.nonzero(band)[1]
    fx = float(np.median(xs)) / image.width
    fy = (top + height * 0.085) / image.height
    return round(fx, 3), round(fy, 3), round(image.width / image.height, 4)


def write_table() -> None:
    entries = []
    for path in sorted(APP.glob("*.webp")):
        fx, fy, aspect = face(Image.open(path).convert("RGBA"))
        entries.append(f"  '{path.stem}': ({fx}, {fy}, {aspect}),")
    TABLE.write_text(
        "// GENERATED by tool/assets/poses.py. Do not edit by hand.\n\n"
        "/// Every villager pose (`assets/figures/poses/<name>.webp`) and where\n"
        "/// its face is: (x, y) as fractions of the image, and its aspect ratio.\n"
        "const poseFaces = <String, (double, double, double)>{\n"
        + "\n".join(entries)
        + "\n};\n"
    )
    print(f"{TABLE}: {len(entries)} poses")


def main() -> None:
    SOURCE.mkdir(parents=True, exist_ok=True)
    APP.mkdir(parents=True, exist_ok=True)
    for sheet in map(Path, sys.argv[1:]):
        names = [f"{sheet.stem}_{n}" for n in range(1, POSES + 1)]
        sliced = subprocess.run(
            [sys.executable, "tool/assets/slice_sheet.py", str(sheet), str(SOURCE), *names],
            check=False,
            capture_output=True,
        )
        if sliced.returncode != 0 or not all((SOURCE / f"{n}.png").exists() for n in names):
            split_by_columns(sheet, names)
        for name in names:
            image = Image.open(SOURCE / f"{name}.png").convert("RGBA")
            width = round(image.width * HEIGHT / image.height)
            image.resize((width, HEIGHT), Image.LANCZOS).save(
                APP / f"{name}.webp", "WEBP", quality=78, method=6
            )
        print(sheet.stem, "ok")
    write_table()


if __name__ == "__main__":
    main()
