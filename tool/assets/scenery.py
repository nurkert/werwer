"""Turn generated scenery pieces (one cardboard cut-out per image) into the
app's WebP files and write the table of their aspect ratios.

Usage: python tool/assets/scenery.py [--web] design/sheets/scenery/*.png

With `--web` the pieces are only for the website (knots and tassels over
the seams of its garlands and valance): they go to
`website/src/assets/scenery/` and not into the app.

A piece `design/sheets/scenery/<name>.png` becomes
`design/source/scenery/<name>.png` (trimmed, transparent) and
`app/assets/stage/scenery/<name>.webp` (at most 1400 px on its long side).
If the generator painted a background instead of transparency, the piece
is cut out of it (see cutout.py). All pieces end up in
`app/lib/src/stage/scenery.g.dart`.
"""

import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

from slice_sheet import clean_alpha

SOURCE = Path("design/source/scenery")
APP = Path("app/assets/stage/scenery")
WEB = Path("website/src/assets/scenery")
TABLE = Path("app/lib/src/stage/scenery.g.dart")
LONG = 1400


def opaque_background(rgba: np.ndarray) -> bool:
    """Whether the corners are painted rather than transparent."""
    corners = [rgba[0, 0, 3], rgba[0, -1, 3], rgba[-1, 0, 3], rgba[-1, -1, 3]]
    return min(corners) > 200


def cut_from_painted(rgba: np.ndarray) -> np.ndarray:
    """Grow the background from the border through smooth pixels; the pale
    cardboard rim stops it. The largest remaining region is the piece."""
    gray = rgba[:, :, :3].astype(np.float32).mean(axis=2)
    smooth_gray = ndimage.gaussian_filter(gray, 1.2)
    edge = np.hypot(ndimage.sobel(smooth_gray, axis=1), ndimage.sobel(smooth_gray, axis=0))
    smooth = edge < np.percentile(edge, 55)
    labels, _ = ndimage.label(smooth)
    border = set(np.unique(np.concatenate([labels[0], labels[-1], labels[:, 0], labels[:, -1]]))) - {0}
    piece = ~np.isin(labels, list(border))
    piece = ndimage.binary_fill_holes(ndimage.binary_opening(piece, iterations=2))
    parts, count = ndimage.label(piece)
    sizes = ndimage.sum(piece, parts, range(1, count + 1))
    keep = parts == (int(np.argmax(sizes)) + 1)
    keep = ndimage.binary_erosion(keep, iterations=1)
    out = rgba.copy()
    out[:, :, 3] = (ndimage.gaussian_filter(keep.astype(np.float32), 0.8) * 255).astype(np.uint8)
    return out


def trim(rgba: np.ndarray) -> np.ndarray:
    ys, xs = np.nonzero(rgba[:, :, 3] > 24)
    return rgba[max(ys.min() - 4, 0) : ys.max() + 5, max(xs.min() - 4, 0) : xs.max() + 5]


def main() -> None:
    args = sys.argv[1:]
    web = args[:1] == ["--web"]
    out = WEB if web else APP
    SOURCE.mkdir(parents=True, exist_ok=True)
    out.mkdir(parents=True, exist_ok=True)
    for sheet in map(Path, args[1:] if web else args):
        rgba = np.array(Image.open(sheet).convert("RGBA"))
        rgba = cut_from_painted(rgba) if opaque_background(rgba) else clean_alpha(rgba)
        rgba = trim(rgba)
        image = Image.fromarray(rgba)
        image.save(SOURCE / f"{sheet.stem}.png", optimize=True)
        scale = min(1.0, LONG / max(image.size))
        size = (round(image.width * scale), round(image.height * scale))
        image.resize(size, Image.LANCZOS).save(
            out / f"{sheet.stem}.webp", "WEBP", quality=86, method=6
        )
        print(sheet.stem, size)
    if web:
        return
    entries = []
    for path in sorted(APP.glob("*.webp")):
        with Image.open(path) as image:
            entries.append(f"  '{path.stem}': {round(image.width / image.height, 4)},")
    TABLE.write_text(
        "// GENERATED by tool/assets/scenery.py. Do not edit by hand.\n\n"
        "/// Every scenery piece (`assets/stage/scenery/<name>.webp`) and its\n"
        "/// aspect ratio (width / height).\n"
        "const sceneryAspects = <String, double>{\n" + "\n".join(entries) + "\n};\n"
    )
    print(f"{TABLE}: {len(entries)} pieces")


if __name__ == "__main__":
    main()
