// Generates the website's colour block and the app's palette from
// design/tokens.json, so both always use the same values.
//
//   dart run tool/tokens.dart          write the files
//   dart run tool/tokens.dart --check  fail if they are out of date (CI)
import 'dart:convert';
import 'dart:io';

const _css = 'website/src/styles/tokens.css';
const _dart = 'app/lib/src/palette.g.dart';
const _start = '  /* tokens:start (generated from design/tokens.json) */';
const _end = '  /* tokens:end */';

String _camel(String name) => name.replaceAllMapped(
  RegExp(r'-([a-z0-9])'),
  (m) => m[1]!.toUpperCase(),
);

void main(List<String> args) {
  final check = args.contains('--check');
  final json =
      jsonDecode(File('design/tokens.json').readAsStringSync())
          as Map<String, Object?>;
  final colors = (json['colors']! as Map<String, Object?>).cast<String, String>();
  final radii = (json['radii']! as Map<String, Object?>).cast<String, int>();

  final block = StringBuffer()..writeln(_start);
  colors.forEach((k, v) => block.writeln('  --$k: $v;'));
  radii.forEach((k, v) => block.writeln('  --$k: ${v}px;'));
  block.write(_end);

  final css = File(_css).readAsStringSync();
  final from = css.indexOf(_start);
  final to = css.indexOf(_end);
  if (from < 0 || to < 0) {
    stderr.writeln('$_css has no tokens:start/tokens:end markers.');
    exit(1);
  }
  final newCss =
      css.substring(0, from) + block.toString() + css.substring(to + _end.length);

  final dart = StringBuffer()
    ..writeln('// GENERATED by tool/tokens.dart from design/tokens.json.')
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln("import 'dart:ui';")
    ..writeln()
    ..writeln('/// Colours of the Whowolf design, shared with the website.')
    ..writeln('abstract final class Palette {');
  colors.forEach((k, v) {
    final hex = v.substring(1).toUpperCase();
    dart.writeln('  static const ${_camel(k)} = Color(0xFF$hex);');
  });
  dart.writeln('}');
  dart
    ..writeln()
    ..writeln('/// Corner radii, shared with the website.')
    ..writeln('abstract final class Radii {');
  radii.forEach((k, v) {
    dart.writeln('  static const double ${_camel(k.replaceFirst('radius-', ''))} = $v;');
  });
  dart.writeln('}');

  final outdated = <String>[
    if (newCss != css) _css,
    if (!File(_dart).existsSync() || File(_dart).readAsStringSync() != '$dart')
      _dart,
  ];
  if (check) {
    if (outdated.isNotEmpty) {
      stderr.writeln(
        'Design tokens out of date: ${outdated.join(', ')}. '
        'Run: dart run tool/tokens.dart',
      );
      exit(1);
    }
    return;
  }
  File(_css).writeAsStringSync(newCss);
  File(_dart).writeAsStringSync('$dart');
  stdout.writeln('Wrote ${outdated.isEmpty ? 'nothing (up to date)' : outdated.join(', ')}');
}
